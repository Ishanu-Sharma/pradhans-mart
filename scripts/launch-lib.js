import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

// Default hostnames handed out by hosting platforms. A launch needs your own domain.
const PLATFORM_HOSTS = [
  'onrender.com', 'vercel.app', 'netlify.app', 'herokuapp.com', 'railway.app', 'fly.dev',
  'pages.dev', 'workers.dev', 'web.app', 'firebaseapp.com', 'run.app', 'appspot.com',
  'github.io', 'glitch.me', 'repl.co', 'replit.app', 'replit.dev', 'azurewebsites.net',
  'cloudfront.net', 'amplifyapp.com', 'koyeb.app', 'ngrok.io', 'ngrok-free.app', 'trycloudflare.com'
];

function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out); else out.push(p);
  }
  return out;
}

export function launchProblems(env = process.env) {
  const problems = [];
  const business = JSON.parse(fs.readFileSync(path.join(root, 'config/business.json'), 'utf8'));
  const store = JSON.parse(fs.readFileSync(path.join(root, 'config/store.json'), 'utf8'));
  const optional = new Set(business._optional || []);

  // 1. Business details (Consumer Protection (E-Commerce) Rules, 2020, rule 4 and 5).
  const check = (obj, prefix) => {
    for (const [k, v] of Object.entries(obj)) {
      if (k.startsWith('_') || optional.has(k)) continue;
      if (v && typeof v === 'object') check(v, `${prefix}${k}.`);
      else if (!String(v ?? '').trim()) problems.push(`Business detail missing: ${prefix}${k} (config/business.json)`);
    }
  };
  check(business, '');

  // 2. Facts only the owner can confirm.
  for (const [k, v] of Object.entries(store.launch)) {
    if (v !== true) problems.push(`Not confirmed yet: launch.${k} (config/store.json)`);
  }

  // 3. Custom domain over HTTPS.
  const url = env.PUBLIC_URL;
  if (!url) problems.push('PUBLIC_URL is not set. Set it to your custom domain, for example https://www.yourdomain.in');
  else {
    let u;
    try { u = new URL(url); } catch { problems.push(`PUBLIC_URL is not a valid URL: ${url}`); }
    if (u) {
      if (u.protocol !== 'https:') problems.push('PUBLIC_URL must start with https://');
      const host = u.hostname.toLowerCase();
      if (host === 'localhost' || /^[\d.]+$/.test(host) || host.includes(':')) problems.push('PUBLIC_URL must be a domain name, not localhost or an IP address.');
      if (PLATFORM_HOSTS.some((h) => host === h || host.endsWith(`.${h}`))) problems.push(`PUBLIC_URL uses a hosting platform's default domain (${host}). Connect your custom domain first.`);
    }
  }

  // 4. Staff passwords.
  if (!env.ADMIN_PASSWORD || env.ADMIN_PASSWORD.length < 12) problems.push('ADMIN_PASSWORD must be set and at least 12 characters long.');

  // 5. Favicon and policy pages exist.
  for (const f of ['public/favicon.svg', 'public/favicon.ico', 'public/apple-touch-icon.png']) {
    if (!fs.existsSync(path.join(root, f))) problems.push(`Missing ${f}. Run: npm run icons`);
  }
  for (const v of ['privacy', 'terms', 'refunds', 'cookies', 'contact']) {
    if (!fs.existsSync(path.join(root, 'views', `${v}.html`))) problems.push(`Missing policy page views/${v}.html`);
  }

  // 6. Nothing generated-by or made-with in what visitors receive, and no dashes the brief rules out.
  const shipped = [...walk(path.join(root, 'views')), ...walk(path.join(root, 'public'))].filter((f) => /\.(html|js|css|svg|webmanifest)$/.test(f));
  for (const f of shipped) {
    const t = fs.readFileSync(f, 'utf8');
    const rel = path.relative(root, f);
    if (/made with|built with|generated by|powered by/i.test(t)) problems.push(`"Made with" style tag found in ${rel}`);
    if (/[—–]/.test(t)) problems.push(`Em or en dash found in ${rel}`);
  }
  return problems;
}
